import { execFileSync } from "node:child_process";
import {
  chmodSync, copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";

/**
 * scripts/build-core-wasm.mjs against a small copy of the tree, with stub
 * tools. Each stub writes its name to a log, so a test can see which tools a
 * run started. The real script is copied, because it finds the tree from its
 * own location.
 */
const SCRIPT = resolve("scripts/build-core-wasm.mjs");
const GENERATED = "lib/wasm/generated";

let repo: string;

function stub(name: string, body: string) {
  const path = join(repo, "bin", name);
  writeFileSync(path, `#!/bin/sh\necho ${name} >> "$TOOL_LOG"\n${body}\n`);
  chmodSync(path, 0o755);
}

function build(args: string[] = [], env: Record<string, string> = {}) {
  execFileSync(process.execPath, [join(repo, "scripts/build-core-wasm.mjs"), ...args], {
    cwd: repo,
    env: {
      ...process.env,
      PATH: `${join(repo, "bin")}:${process.env.PATH}`,
      TOOL_LOG: join(repo, "tools.log"),
      WASM_BINDGEN: "wasm-bindgen",
      WASM_OPT: "wasm-opt",
      CORE_WASM_PREBUILT: "",
      ...env,
    },
    stdio: "pipe",
  });
}

/** The tools that ran since the last call. */
function toolsRun(): string[] {
  const log = join(repo, "tools.log");
  if (!existsSync(log)) return [];
  const names = readFileSync(log, "utf8").trim().split("\n").filter(Boolean);
  rmSync(log);
  return names;
}

const FULL_BUILD = ["rustc", "cargo", "wasm-bindgen", "wasm-opt"];

beforeEach(() => {
  repo = mkdtempSync(join(tmpdir(), "core-wasm-"));
  for (const dir of ["bin", "scripts", "rust-api/core/src"]) mkdirSync(join(repo, dir), { recursive: true });
  copyFileSync(SCRIPT, join(repo, "scripts/build-core-wasm.mjs"));
  writeFileSync(join(repo, "rust-api/Cargo.toml"), "[workspace]\n");
  writeFileSync(join(repo, "rust-api/Cargo.lock"), "version = 4\n");
  writeFileSync(join(repo, "rust-api/core/Cargo.toml"), "[package]\nname = \"ledger-core\"\n");
  writeFileSync(join(repo, "rust-api/core/src/lib.rs"), "pub fn one() -> u8 { 1 }\n");

  stub("rustc", "echo /fake/sysroot");
  // The compiler output holds the source, so a test can see a new build.
  stub("cargo", [
    "out=rust-api/target/wasm32-unknown-unknown/release",
    "mkdir -p \"$out\"",
    "cat rust-api/core/src/lib.rs > \"$out/ledger_core.wasm\"",
  ].join("\n"));
  stub("wasm-bindgen", [
    "while [ $# -gt 1 ]; do if [ \"$1\" = --out-dir ]; then dir=$2; fi; shift; done",
    "cp \"$1\" \"$dir/ledger_core_bg.wasm\"",
    "echo '// bindings' > \"$dir/ledger_core.js\"",
    "echo '// types' > \"$dir/ledger_core.d.ts\"",
  ].join("\n"));
  stub("wasm-opt", [
    "while [ $# -gt 0 ]; do case \"$1\" in -o) out=$2; shift ;; -*) ;; *) in=$1 ;; esac; shift; done",
    "cp \"$in\" \"$out\"",
  ].join("\n"));
});

afterEach(() => {
  rmSync(repo, { recursive: true, force: true });
});

function embeddedSource(): string {
  const text = readFileSync(join(repo, GENERATED, "core-bytes.ts"), "utf8");
  const base64 = /CORE_WASM_BASE64 = "([^"]*)"/.exec(text)?.[1] ?? "";
  return Buffer.from(base64, "base64").toString("utf8");
}

describe("build-core-wasm.mjs", () => {
  it("builds when nothing is generated", () => {
    build();
    expect(toolsRun()).toEqual(FULL_BUILD);
    expect(embeddedSource()).toBe("pub fn one() -> u8 { 1 }\n");
  });

  it("starts no tool when the inputs did not change", () => {
    build();
    toolsRun();
    build();
    expect(toolsRun()).toEqual([]);
    expect(embeddedSource()).toBe("pub fn one() -> u8 { 1 }\n");
  });

  it.each([
    ["a core source file", "rust-api/core/src/lib.rs"],
    ["the manifest of the core", "rust-api/core/Cargo.toml"],
    ["the lock file", "rust-api/Cargo.lock"],
    ["the workspace manifest", "rust-api/Cargo.toml"],
  ])("builds again when %s changes", (_name, file) => {
    build();
    toolsRun();
    writeFileSync(join(repo, file), "pub fn two() -> u8 { 2 }\n");
    build();
    expect(toolsRun()).toEqual(FULL_BUILD);
  });

  it("puts the new source into the generated bytes", () => {
    build();
    writeFileSync(join(repo, "rust-api/core/src/lib.rs"), "pub fn two() -> u8 { 2 }\n");
    build();
    expect(embeddedSource()).toBe("pub fn two() -> u8 { 2 }\n");
  });

  it("builds again when a new source file appears in a directory below src", () => {
    build();
    toolsRun();
    mkdirSync(join(repo, "rust-api/core/src/deep"));
    writeFileSync(join(repo, "rust-api/core/src/deep/more.rs"), "pub fn three() {}\n");
    build();
    expect(toolsRun()).toEqual(FULL_BUILD);
  });

  it.each(["core-bytes.ts", "ledger_core.js", "ledger_core.d.ts", "ledger_core_bg.wasm"])(
    "builds again when the generated %s is missing",
    (file) => {
      build();
      toolsRun();
      rmSync(join(repo, GENERATED, file));
      build();
      expect(toolsRun()).toEqual(FULL_BUILD);
      expect(existsSync(join(repo, GENERATED, file))).toBe(true);
    },
  );

  it("builds again with --force", () => {
    build();
    toolsRun();
    build(["--force"]);
    expect(toolsRun()).toEqual(FULL_BUILD);
  });

  it("builds again after a build that failed half way", () => {
    build();
    toolsRun();
    writeFileSync(join(repo, "rust-api/core/src/lib.rs"), "pub fn two() -> u8 { 2 }\n");
    stub("wasm-opt", "exit 7");
    expect(() => build()).toThrow();
    toolsRun();
    // The tool works again. The inputs did not change since the failed run.
    stub("wasm-opt", [
      "while [ $# -gt 0 ]; do case \"$1\" in -o) out=$2; shift ;; -*) ;; *) in=$1 ;; esac; shift; done",
      "cp \"$in\" \"$out\"",
    ].join("\n"));
    build();
    expect(toolsRun()).toEqual(FULL_BUILD);
    expect(embeddedSource()).toBe("pub fn two() -> u8 { 2 }\n");
  });

  describe("with CORE_WASM_PREBUILT=1", () => {
    it("starts no tool and writes the bytes of the given module", () => {
      mkdirSync(join(repo, GENERATED), { recursive: true });
      writeFileSync(join(repo, GENERATED, "ledger_core_bg.wasm"), "prebuilt");
      writeFileSync(join(repo, GENERATED, "ledger_core.js"), "// bindings");
      // The image stage that uses this mode has no Rust sources.
      rmSync(join(repo, "rust-api"), { recursive: true });
      build([], { CORE_WASM_PREBUILT: "1" });
      expect(toolsRun()).toEqual([]);
      expect(embeddedSource()).toBe("prebuilt");
    });

    it("refuses when the module is not there", () => {
      expect(() => build([], { CORE_WASM_PREBUILT: "1" })).toThrow(/requires the generated WASM/);
    });
  });
});
