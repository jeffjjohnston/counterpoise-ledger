// Builds the browser copy of ledger-core into lib/wasm/generated/.
//
//   node scripts/build-core-wasm.mjs [--force]
//
// A BUILD ONLY WHEN AN INPUT CHANGED. The script records a hash of the
// inputs beside the output. When the hash is the same and each output file
// is there, it starts no tool. So each command that needs the module (the
// Vitest global setup, the Vite plugin, `npm run core:wasm:build`) can call
// it each time: after a change to the Rust core the next call builds, and
// otherwise the call costs some milliseconds. --force builds always.
//
// The hash is of file contents, not of times: a branch change gives each
// file a new time. It does not include the toolchain, so use --force after
// a change of rustc, wasm-bindgen or wasm-opt.
import { createHash } from "node:crypto";
import {
  existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, writeFileSync,
} from "node:fs";
import { execFileSync } from "node:child_process";
import { relative, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const outDir = resolve(root, "lib/wasm/generated");
const wasmPath = resolve(outDir, "ledger_core_bg.wasm");
const stampPath = resolve(outDir, "inputs.sha256");
const OUTPUTS = ["ledger_core_bg.wasm", "ledger_core.js", "ledger_core.d.ts", "core-bytes.ts"];
mkdirSync(outDir, { recursive: true });

/** Each file below `dir`, in a fixed order. */
function filesBelow(dir) {
  return readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
    .flatMap((entry) => {
      const path = resolve(dir, entry.name);
      return entry.isDirectory() ? filesBelow(path) : [path];
    });
}

/** A hash of each file that can change the module: the core, the manifests
 * that select its dependencies, and this script. */
function inputsHash() {
  const hash = createHash("sha256");
  const inputs = [
    import.meta.filename,
    resolve(root, "rust-api/Cargo.toml"),
    resolve(root, "rust-api/Cargo.lock"),
    resolve(root, "rust-api/core/Cargo.toml"),
    ...filesBelow(resolve(root, "rust-api/core/src")),
  ];
  for (const path of inputs) {
    const content = readFileSync(path);
    hash.update(`${relative(root, path)}\0${content.length}\0`).update(content);
  }
  return hash.digest("hex");
}

function isFresh(hash) {
  return existsSync(stampPath) && readFileSync(stampPath, "utf8").trim() === hash
    && OUTPUTS.every((file) => existsSync(resolve(outDir, file)));
}

const prebuilt = process.env.CORE_WASM_PREBUILT === "1";
// The image stage that sets CORE_WASM_PREBUILT has no Rust sources to hash.
const hash = prebuilt ? null : inputsHash();
if (hash !== null && !process.argv.includes("--force") && isFresh(hash)) process.exit(0);

if (!prebuilt) {
  // A build that stops half way must not look fresh on the next call.
  rmSync(stampPath, { force: true });
  const configPaths = [
    "/opt/homebrew/opt/rust-wasm/share/rust-wasm/cargo-config.toml",
    "/usr/local/opt/rust-wasm/share/rust-wasm/cargo-config.toml",
  ];
  const sysroot = execFileSync("rustc", ["--print", "sysroot"], { encoding: "utf8" }).trim();
  const homebrewRust = sysroot.includes("/Cellar/rust/");
  const cargoConfig = homebrewRust ? configPaths.find(existsSync) : undefined;
  if (homebrewRust && !cargoConfig) {
    throw new Error("Homebrew Rust requires rust-wasm's cargo-config.toml");
  }
  const lldDir = homebrewRust
    ? ["/opt/homebrew/opt/lld@22/bin", "/usr/local/opt/lld@22/bin"]
      .find((path) => existsSync(resolve(path, "wasm-ld")))
    : undefined;
  const buildEnv = lldDir
    ? { ...process.env, PATH: `${lldDir}:${process.env.PATH}` }
    : process.env;
  const cargoArgs = [
    ...(cargoConfig ? ["--config", cargoConfig] : []),
    "build", "--locked", "--release", "-p", "ledger-core", "--features", "wasm",
    "--target", "wasm32-unknown-unknown", "--manifest-path", "rust-api/Cargo.toml",
  ];
  execFileSync("cargo", cargoArgs, { cwd: root, env: buildEnv, stdio: "inherit" });
  execFileSync(process.env.WASM_BINDGEN ?? "wasm-bindgen", [
    "--target", "web", "--out-dir", outDir,
    resolve(root, "rust-api/target/wasm32-unknown-unknown/release/ledger_core.wasm"),
  ], { cwd: root, stdio: "inherit" });
  const optimizedPath = `${wasmPath}.optimized`;
  execFileSync(process.env.WASM_OPT ?? "wasm-opt", [
    "--enable-bulk-memory", "--enable-nontrapping-float-to-int",
    "-Oz", wasmPath, "-o", optimizedPath,
  ], { cwd: root, stdio: "inherit" });
  renameSync(optimizedPath, wasmPath);
} else if (!existsSync(wasmPath) || !existsSync(resolve(outDir, "ledger_core.js"))) {
  throw new Error("CORE_WASM_PREBUILT=1 requires the generated WASM and JavaScript bindings");
}

const base64 = readFileSync(wasmPath).toString("base64");
writeFileSync(resolve(outDir, "core-bytes.ts"),
  `// Generated by scripts/build-core-wasm.mjs.\nexport const CORE_WASM_BASE64 = ${JSON.stringify(base64)};\n`);
// Written last: the stamp says that every output above is complete.
if (hash !== null) writeFileSync(stampPath, `${hash}\n`);
