import { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const outDir = resolve(root, "lib/wasm/generated");
const wasmPath = resolve(outDir, "ledger_core_bg.wasm");
mkdirSync(outDir, { recursive: true });

if (process.env.CORE_WASM_PREBUILT !== "1") {
  const configPaths = [
    "/opt/homebrew/opt/rust-wasm/share/rust-wasm/cargo-config.toml",
    "/usr/local/opt/rust-wasm/share/rust-wasm/cargo-config.toml",
  ];
  const sysroot = execFileSync("rustc", ["--print", "sysroot"], { encoding: "utf8" }).trim();
  const homebrewRust = sysroot.includes("/Cellar/rust/");
  const cargoConfig = homebrewRust ? configPaths.find(existsSync) : undefined;
  if (homebrewRust && !cargoConfig) {
    throw new Error("Homebrew Rust requires rust-wasm's cargo-config.toml");
  }
  const lldDir = homebrewRust
    ? ["/opt/homebrew/opt/lld@22/bin", "/usr/local/opt/lld@22/bin"]
      .find((path) => existsSync(resolve(path, "wasm-ld")))
    : undefined;
  const buildEnv = lldDir
    ? { ...process.env, PATH: `${lldDir}:${process.env.PATH}` }
    : process.env;
  const cargoArgs = [
    ...(cargoConfig ? ["--config", cargoConfig] : []),
    "build", "--locked", "--release", "-p", "ledger-core", "--features", "wasm",
    "--target", "wasm32-unknown-unknown", "--manifest-path", "rust-api/Cargo.toml",
  ];
  execFileSync("cargo", cargoArgs, { cwd: root, env: buildEnv, stdio: "inherit" });
  execFileSync(process.env.WASM_BINDGEN ?? "wasm-bindgen", [
    "--target", "web", "--out-dir", outDir,
    resolve(root, "rust-api/target/wasm32-unknown-unknown/release/ledger_core.wasm"),
  ], { cwd: root, stdio: "inherit" });
  const optimizedPath = `${wasmPath}.optimized`;
  execFileSync(process.env.WASM_OPT ?? "wasm-opt", [
    "--enable-bulk-memory", "--enable-nontrapping-float-to-int",
    "-Oz", wasmPath, "-o", optimizedPath,
  ], { cwd: root, stdio: "inherit" });
  renameSync(optimizedPath, wasmPath);
} else if (!existsSync(wasmPath) || !existsSync(resolve(outDir, "ledger_core.js"))) {
  throw new Error("CORE_WASM_PREBUILT=1 requires the generated WASM and JavaScript bindings");
}

const base64 = readFileSync(wasmPath).toString("base64");
writeFileSync(resolve(outDir, "core-bytes.ts"),
  `// Generated by scripts/build-core-wasm.mjs.\nexport const CORE_WASM_BASE64 = ${JSON.stringify(base64)};\n`);
